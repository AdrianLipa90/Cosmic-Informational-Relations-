#!/usr/bin/env python3
import math

R=13873.0
DATA={
"100x70":(138.84800481874672,932.2704341350611),
"100x94":(122.57521597565983,929.7147563392913),
"143x100":(136.97736263070678,913.0165939424569),
"143x70":(138.16337335301176,924.5776768095703),
"143x94":(122.05069359959167,922.1337797618902),
"94x70":(124.12582503225137,941.7092384802344),
}
EXPECTED={
"100x70":(0.17434151920757943,2.5200119085459134),
"100x94":(0.1640319438519112,2.607951299866624),
"143x100":(0.17497944092064469,2.5147426712539356),
"143x70":(0.17463316389812125,2.5176005333541256),
"143x94":(0.16435204797621406,2.6051386610628766),
"94x70":(0.16401162009306752,2.6081300626247215),
}
vals=[]
for k,(D2,D3) in DATA.items():
    q=(1/7)*math.sqrt(10*D2/D3)
    n=-math.log2(q)
    eq,en=EXPECTED[k]
    assert abs(q-eq)<1e-14
    assert abs(n-en)<1e-13
    assert 0<q<1
    assert abs(n-round(n))>0.39
    vals.append(n)

mean=sum(vals)/len(vals)
var=sum((x-mean)**2 for x in vals)/(len(vals)-1)
assert abs(mean-2.562262522784699)<1e-13
assert abs(math.sqrt(var)-0.049127594666998314)<1e-13

D2m=130.45674590166135
D3m=927.2370799114174
qm=(1/7)*math.sqrt(10*D2m/D3m)
nm=-math.log2(qm)
assert abs(qm-0.16944932194983256)<1e-14
assert abs(nm-2.561074230987091)<1e-13
assert abs(R*qm-2350.770443410027)<1e-9

print("PASS: held-out ELC 2026 tetrahedral scale audit reproduced; integer dyadic point-estimate hit absent.")
